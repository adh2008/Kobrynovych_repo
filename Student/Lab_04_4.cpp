#include <iostream>
#include <cmath>
#include <iomanip>
#include <windows.h>

using namespace std;

int main() {
    SetConsoleOutputCP(65001);
    double x_start, x_end, dx;

    // Введення параметрів з клавіатури
    cout << "Введіть X_поч: ";
    cin >> x_start;
    cout << "Введіть X_кін: ";
    cin >> x_end;
    cout << "Введіть dX (крок): ";
    cin >> dx;

    // Перевірка коректності кроку
    if (dx <= 0) {
        cout << "Помилка: крок dX повинен бути більше 0!" << endl;
        return 1;
    }

    // Заголовок та шапка таблиці
    cout << "\n===============================" << endl;
    cout << "   ТАБЛИЦЯ ЗНАЧЕНЬ ФУНКЦІЇ    " << endl;
    cout << "===============================" << endl;
    cout << "+--------------+--------------+" << endl;
    cout << "|      X       |      Y       |" << endl;
    cout << "+--------------+--------------+" << endl;

    // Налаштування виводу (2 знаки після коми)
    cout << fixed << setprecision(2);

    // Цикл обчислення функції на проміжку
    for (double x = x_start; x <= x_end + dx / 2.0; x += dx) {
        // Усунення похибки чисел із рухомою комою поблизу 0
        if (abs(x) < 1e-9) {
            x = 0.0;
        }

        double y;

        // Гілки розгалуження відповідно до графіка
        if (x < -7.0) {
            y = 0.0;
        } 
        else if (x < -3.0) {        // Відрезoк [-7; -3)
            y = x + 7.0;
        } 
        else if (x < -2.0) {        // Відрізок [-3; -2)
            y = 4.0;
        } 
        else if (x < -1.0) {        // Відрізок [-2; -1)
            y = -3.0 * x - 2.0;
        } 
        else if (x <= 2.0) {        // Парабола y = x^2 на [-1; 2]
            y = x * x;
        } 
        else if (x <= 4.0) {        // Відрізок (2; 4]
            y = -2.0 * x + 8.0;
        } 
        else {                      // x > 4
            y = 0.0;
        }

        // Виведення одного рядка таблиці
        cout << "| " << setw(12) << x << " | " << setw(12) << y << " |" << endl;
    }

    cout << "+--------------+--------------+" << endl;

    return 0;
}